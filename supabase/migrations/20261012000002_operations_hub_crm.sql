-- ---------- search ----------
create or replace function public.search_hub(q text, max_results int default 40)
returns table (kind text, id bigint, title text, subtitle text, archived boolean)
language sql stable security invoker set search_path = public, extensions as $$
  with term as (select '%' || btrim(q) || '%' as p)
  select * from (
    select 'company'::text as kind, c.id as id, c.name as title, array_to_string(c.relationship_types, ', ') as subtitle, c.archived_at is not null as archived
      from companies c, term where c.name ilike term.p or c.legal_name ilike term.p or exists (select 1 from unnest(c.aliases) a where a ilike term.p) or c.email ilike term.p
    union all
    select 'contact', ct.id, ct.full_name, coalesce(ct.email, ct.title), ct.archived_at is not null
      from contacts ct, term where ct.full_name ilike term.p or ct.email ilike term.p or exists (select 1 from unnest(ct.alt_emails) e where e ilike term.p)
    union all
    select 'opportunity', l.id, coalesce(l.name, l.company), l.pipeline_stage, l.archived_at is not null
      from leads l, term where l.name ilike term.p or l.company ilike term.p or l.product_interest ilike term.p or l.notes ilike term.p or l.contact ilike term.p or l.pipeline_stage ilike term.p
    union all
    select 'task', t.id, t.subject, coalesce(t.owner, '') || ' · ' || coalesce(t.action_state, t.status, ''), t.archived_at is not null
      from tasks t, term where t.subject ilike term.p or t.next_action ilike term.p or t.notes ilike term.p or t.company ilike term.p or t.client ilike term.p
    union all
    select 'order', o.id, o.name, o.status, o.archived_at is not null
      from orders o, term where o.name ilike term.p or o.ref ilike term.p or o.notes ilike term.p
    union all
    select 'communication', i.id, coalesce(i.subject, left(i.notes, 80)), coalesce(i.type, '') || ' · ' || coalesce(i.company, ''), i.archived_at is not null
      from interactions i, term where i.subject ilike term.p or i.notes ilike term.p or i.company ilike term.p or i.client ilike term.p
  ) r
  where length(btrim(q)) >= 2
  order by archived, kind, title
  limit greatest(1, least(max_results, 100));
$$;

-- ---------- data quality (flags, never blocks) ----------
create or replace view public.hub_data_quality with (security_invoker = true) as
  select 'opportunity'::text as entity_type, id as entity_id, coalesce(name, company) as title, 'No next action' as issue
    from public.leads where archived_at is null and pipeline_stage not in ('Won','Lost') and nullif(btrim(next_action), '') is null
  union all
  select 'opportunity', id, coalesce(name, company), 'On hold without a review date'
    from public.leads where archived_at is null and pipeline_stage = 'On Hold / Nurture' and review_date is null
  union all
  select 'opportunity', id, coalesce(name, company), 'Lost without a reason'
    from public.leads where archived_at is null and pipeline_stage = 'Lost' and nullif(btrim(lost_reason), '') is null
  union all
  select 'opportunity', id, coalesce(name, company), 'Value without currency'
    from public.leads where archived_at is null and value_amount is not null and currency is null
  union all
  select 'opportunity', id, coalesce(name, company), 'Not linked to a company'
    from public.leads where archived_at is null and company_id is null
  union all
  select 'task', id, subject, 'No owner'
    from public.tasks where archived_at is null and action_state not in ('Completed','Cancelled') and (owner is null or owner in ('', 'You', 'Unassigned'))
  union all
  select 'task', id, subject, 'No next action'
    from public.tasks where archived_at is null and action_state = 'Our action' and nullif(btrim(next_action), '') is null
  union all
  select 'task', id, subject, 'Waiting with no follow-up date'
    from public.tasks where archived_at is null and action_state = 'Awaiting response' and follow_up_date is null and expected_response_date is null
  union all
  select 'order', id, name, 'Customer unconfirmed'
    from public.orders where archived_at is null and customer_confirmed = false
  union all
  select 'company', a.id, a.name, 'Possible duplicate of ' || b.name
    from public.companies a join public.companies b on a.id < b.id
    where a.archived_at is null and b.archived_at is null and extensions.similarity(a.name_key, b.name_key) > 0.6;

