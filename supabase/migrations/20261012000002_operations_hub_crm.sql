-- =====================================================================
-- 0002 — OPERATIONS HUB CRM (additive, backward compatible)
--
-- Nothing is dropped or renamed. Every existing column keeps working, so
-- the current app continues to run against this schema. New capabilities:
--   • companies, contacts (many-to-many), orders + fulfilment milestones
--   • leads become the sales pipeline (9 stages, money + currency, links)
--   • tasks get action states, links, archive/supersede, privacy flag
--   • interactions become a full communication log (email lifecycle is
--     separate: removing a communication never removes business records)
--   • activity_log audit trail written by triggers
--   • records are archived, not deleted (deletes on business tables blocked)
--   • task history survives: task_history FK no longer cascades
--   • sean_week and inbox_triage tables the app already expects
--   • search function + indexes, data-quality view
-- Access control (RLS) is NOT changed here — see 0003.
-- =====================================================================

