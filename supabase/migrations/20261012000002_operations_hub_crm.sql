-- Generic change logger. TG_ARGV[0] = entity_type; remaining args = tracked columns.
create or replace function public.hub_log_changes() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  col text; o text; n text; i int;
  who text := coalesce(
    (select display_name from public.profiles where id = auth.uid()),
    nullif(to_jsonb(new)->>'updated_by', ''),
    'system');
begin
  if tg_op = 'INSERT' then
    insert into public.activity_log(entity_type, entity_id, action, actor)
    values (tg_argv[0], new.id, 'created', who);
    return new;
  end if;
  for i in 1 .. tg_nargs - 1 loop
    col := tg_argv[i];
    o := to_jsonb(old)->>col; n := to_jsonb(new)->>col;
    if o is distinct from n then
      insert into public.activity_log(entity_type, entity_id, action, field, old_value, new_value, actor)
      values (tg_argv[0], new.id,
              case when col = 'archived_at' and n is not null then 'archived'
                   when col = 'archived_at' and n is null then 'restored' else 'changed' end,
              col, o, n, who);
    end if;
  end loop;
  return new;
end $$;

