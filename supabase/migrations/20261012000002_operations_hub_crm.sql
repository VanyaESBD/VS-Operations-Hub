-- A logged communication updates "last interaction" on its company/opportunity.
create or replace function public.hub_interaction_rollup() returns trigger language plpgsql set search_path = public as $$
begin
  if new.company_id is not null then
    update public.companies set last_interaction_at = greatest(coalesce(last_interaction_at, new.occurred_at), new.occurred_at) where id = new.company_id;
  end if;
  if new.opportunity_id is not null then
    update public.leads set last_interaction_at = greatest(coalesce(last_interaction_at, new.occurred_at), new.occurred_at) where id = new.opportunity_id;
  end if;
  return new;
end $$;
create trigger interactions_rollup after insert or update of occurred_at, company_id, opportunity_id on public.interactions
  for each row when (new.occurred_at is not null) execute function public.hub_interaction_rollup();

