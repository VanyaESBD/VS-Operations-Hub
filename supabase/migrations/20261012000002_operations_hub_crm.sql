-- ---------- shared helpers ----------
create or replace function public.hub_touch_updated_at() returns trigger
language plpgsql set search_path = public as $$ begin new.updated_at := now(); return new; end $$;

create or replace function public.hub_block_delete() returns trigger
language plpgsql set search_path = public as $$
begin
  if coalesce(current_setting('hub.allow_delete', true), '') = 'on' then
    return old;
  end if;
  raise exception 'Records in % are archived, not deleted. Set archived_at instead.', tg_table_name
    using errcode = 'P0001';
end $$;

