-- Map between the legacy 4-word stages and the 9 pipeline stages so the old
-- and new screens stay consistent while both exist.
create or replace function public.hub_legacy_to_pipeline(s text) returns text language sql immutable set search_path = public as $$
  select case s when 'Cold' then 'New Lead' when 'Warm' then 'Qualified' when 'Hot' then 'Proposal / Quotation'
    when 'Negotiating' then 'Negotiation' when 'Won' then 'Won' when 'Lost' then 'Lost' else null end $$;
create or replace function public.hub_pipeline_to_legacy(s text) returns text language sql immutable set search_path = public as $$
  select case s when 'New Lead' then 'Cold' when 'Qualified' then 'Warm' when 'Contacted' then 'Warm'
    when 'Discussion / Discovery' then 'Warm' when 'Proposal / Quotation' then 'Hot' when 'Negotiation' then 'Negotiating'
    when 'Won' then 'Won' when 'Lost' then 'Lost' when 'On Hold / Nurture' then 'Cold' else null end $$;

create or replace function public.hub_leads_sync() returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if new.pipeline_stage is null then new.pipeline_stage := coalesce(public.hub_legacy_to_pipeline(new.stage), 'New Lead'); end if;
    if new.stage is null or public.hub_legacy_to_pipeline(new.stage) is distinct from new.pipeline_stage then
      new.stage := coalesce(public.hub_pipeline_to_legacy(new.pipeline_stage), new.stage);
    end if;
  else
    if new.pipeline_stage is distinct from old.pipeline_stage then
      new.stage := coalesce(public.hub_pipeline_to_legacy(new.pipeline_stage), new.stage);
    elsif new.stage is distinct from old.stage then
      new.pipeline_stage := coalesce(public.hub_legacy_to_pipeline(new.stage), new.pipeline_stage);
    end if;
  end if;
  if new.name is null or btrim(new.name) = '' then new.name := new.company; end if;
  if new.pipeline_stage in ('Won','Lost') and new.closed_at is null then new.closed_at := current_date; end if;
  return new;
end $$;
-- Backfill BEFORE the sync trigger exists, so existing legacy values are never rewritten.
