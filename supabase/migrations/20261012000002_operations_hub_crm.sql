create or replace function public.hub_status_to_state(s text) returns text language sql immutable set search_path = public as $$
  select case s when 'To Do' then 'Our action' when 'FYA' then 'Our action' when 'New' then 'Our action'
    when 'Follow Up' then 'Awaiting response' when 'FYI' then 'Monitoring' when 'Done' then 'Completed' else null end $$;
create or replace function public.hub_state_to_status(s text, current_status text) returns text language sql immutable set search_path = public as $$
  select case s
    when 'Our action' then case when current_status in ('To Do','FYA') then current_status else 'To Do' end
    when 'Awaiting response' then 'Follow Up'
    when 'Monitoring' then 'FYI'
    when 'Completed' then 'Done'
    else current_status end $$;   -- On hold / Cancelled have no legacy label: legacy status left as is

create or replace function public.hub_tasks_sync() returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    if new.action_state is null then new.action_state := coalesce(public.hub_status_to_state(new.status), 'Our action'); end if;
    new.status := public.hub_state_to_status(new.action_state, new.status);
  else
    if new.action_state is distinct from old.action_state then
      new.status := public.hub_state_to_status(new.action_state, new.status);
    elsif new.status is distinct from old.status then
      new.action_state := coalesce(public.hub_status_to_state(new.status), new.action_state);
    end if;
  end if;
  if new.action_state = 'Completed' then
    new.completed_at := coalesce(new.completed_at, now());
    new.actual_date := coalesce(new.actual_date, current_date);
  elsif tg_op = 'UPDATE' and old.action_state = 'Completed' then
    new.completed_at := null;   -- reopened
  end if;
  return new;
end $$;
-- Backfill BEFORE the sync trigger exists, so legacy status/actual_date are never rewritten.
update public.tasks set action_state = coalesce(public.hub_status_to_state(status), 'Our action') where action_state is null;
update public.tasks set completed_at = coalesce(actual_date::timestamptz, created_at) where action_state = 'Completed' and completed_at is null;
create trigger tasks_sync before insert or update on public.tasks for each row execute function public.hub_tasks_sync();
