create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  subject text, client text, company text, email text,
  date_received date,
  owner text default 'You',
  status text default 'New',
  priority text default 'Medium',
  expected_date date, actual_date date,
  next_action text, notes text, outcome text, task_type text,
  client_response_date date, time_spent text, revenue_linked text,
  project text, follow_up_date date, follow_up_note text
);
create index if not exists tasks_follow_up_date_idx on public.tasks (follow_up_date) where follow_up_date is not null;

create table if not exists public.task_history (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  task_id bigint references public.tasks(id) on delete cascade,
  changed_by text, old_status text, new_status text, note text,
  entry_type text default 'status_change'
);

create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  company text, contact text, email text, phone text, product_interest text,
  value text, stage text default 'Cold', owner text default 'You',
  next_action text, notes text, last_contact text
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  content text, author text default 'You'
);

create table if not exists public.flags (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  from_name text,
  task_id bigint references public.tasks(id) on delete cascade,
  task_subject text, urgency text default 'Medium', note text, seen boolean default false
);

create table if not exists public.interactions (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  interaction_date text, client text, company text,
  type text default 'Call', notes text, outcome text, logged_by text,
  week_sent boolean default false
);

create table if not exists public.projects (
  id serial primary key,
  name text not null unique,
  color text not null default '#6366f1',
  description text, status text default 'Active', owner text,
  created_at timestamptz default now()
);

create table if not exists public.reminders (
  id serial primary key,
  title text not null, description text,
  remind_date date not null,
  owner text default 'Vanya', category text default 'General',
  completed boolean default false,
  created_at timestamptz default now()
);
create index if not exists reminders_remind_date_idx on public.reminders (remind_date) where completed = false;

-- Live security state (recorded, not endorsed): RLS on for six tables with
-- allow-all policies; RLS OFF for leads and notes; anon has full privileges.
alter table public.tasks        enable row level security;
alter table public.task_history enable row level security;
alter table public.flags        enable row level security;
alter table public.interactions enable row level security;
alter table public.projects     enable row level security;
alter table public.reminders    enable row level security;
create policy "Allow all" on public.tasks for all to public using (true) with check (true);
create policy "Allow all" on public.task_history for all to anon, authenticated using (true) with check (true);
create policy "Allow all" on public.flags for all to anon, authenticated using (true) with check (true);
create policy "Allow all" on public.interactions for all to anon, authenticated using (true) with check (true);
create policy "Allow all on projects" on public.projects for all to public using (true) with check (true);
create policy "Allow all on reminders" on public.reminders for all to public using (true) with check (true);

